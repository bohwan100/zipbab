def parse_household_count(household_str):
    m = re.search(r'(\d+)', str(household_str))
    if m:
        return max(1, min(6, int(m.group(1))))
    return 1

def generate_personalized_plan(
    client_name="고객님",
    household="1명",
    budget=300000,
    frequency="하루 한 끼 (퇴근 후 저녁 30끼)",
    concept="일반식",
    cuisine="한식, 일식",
    exclude="없음",
    pantry="아무것도 없음"
):
    people_count = parse_household_count(household)
    total_meals = 30  # 하루 한 끼 30끼 메인 식단

    # 1. 음식 취향 필터 (한식 우선 및 선택 순서 보장)
    allowed_cuisines = []
    for c in ["한식", "일식", "양식", "중식"]:
        if c in cuisine:
            allowed_cuisines.append(c)
    if not allowed_cuisines:
        allowed_cuisines = ["한식"]

    # 2. 제외 식품 필터
    raw_excludes = [x.strip() for x in re.split(r'[,/ ]+', str(exclude)) if x.strip() and x.strip() not in ["없음", "아무것도 없음", "-"]]

    cuisine_buckets = {c: [] for c in allowed_cuisines}
    for r in MASTER_RECIPES:
        if r["cuisine"] not in allowed_cuisines:
            continue
        all_texts = " ".join([r["title"]] + r["allergens"] + [ing[0] for ing in r["base_ingredients"]])
        if not any(ex in all_texts for ex in raw_excludes):
            cuisine_buckets[r["cuisine"]].append(r)

    # 비어있을 경우 폴백
    for c in allowed_cuisines:
        if not cuisine_buckets[c]:
            cuisine_buckets[c] = [r for r in MASTER_RECIPES if r["cuisine"] == c]

    # 2-1. 야채·채소 위주 식단 스마트 우선순위 정렬 (concept or goal_notes or pantry)
    raw_pantry = [x.strip() for x in re.split(r'[,/ ]+', str(pantry)) if x.strip() and x.strip() not in ["아무것도 없음", "없음", "-"]]
    is_veggie_focus = any(kw in str(concept) + str(client_name) + str(pantry) for kw in ["야채", "채소", "베지", "비건", "다이어트"]) or (client_name == "정민")
    if is_veggie_focus:
        hero_veggies = ['가지', '청경채', '배추', '양배추', '미니양배추', '버섯', '토마토', '파프리카', '피망', '두부', '순두부', '숙주', '콩나물', '구운 채소', '샐러드', '애호박', '감자']
        meat_fried_heroes = ['돈카츠', '가츠동', '탕수육', '깐풍기', '가라아게', '함박스테이크', '차슈', '동파육']
        def get_veggie_score(r):
            score = 0
            t = r['title']
            for kw in hero_veggies:
                if kw in t: score += 15
            for ing in r['base_ingredients']:
                for kw in hero_veggies:
                    if kw in ing[0]: score += 5
            veggie_pantry = ['새송이버섯', '미니양배추', '미소 된장', '미소된장', '가스오부시', '가쓰오부시']
            for p in veggie_pantry:
                if any(p in t or p in ing[0] for ing in r['base_ingredients']):
                    score += 10
            for mf in meat_fried_heroes:
                if mf in t: score -= 20
            return score

        for c in allowed_cuisines:
            cuisine_buckets[c].sort(key=get_veggie_score, reverse=True)

    # 3. 30일 식단 편성 (선택된 모든 요리 균등 분배 & 데일리 순환 인터리빙)
    candidate_recipes = []
    idx = 0
    while len(candidate_recipes) < total_meals:
        c = allowed_cuisines[idx % len(allowed_cuisines)]
        pool = cuisine_buckets[c]
        r_idx = (idx // len(allowed_cuisines)) % len(pool)
        candidate_recipes.append(pool[r_idx])
        idx += 1

    num_cand = len(candidate_recipes)
    final_recipes = []

    # 3-1. 30일 식단 전체 식재료 누적 소진 총량 계산 (소진 트래커 정밀도 극대화)
    ing_totals = defaultdict(float)
    ing_units = {}
    for day_i in range(total_meals):
        base_r = candidate_recipes[day_i % num_cand]
        for ing in base_r["base_ingredients"]:
            if ing[3] != "seasoning":
                ing_totals[ing[0]] += ing[1] * people_count
                ing_units[ing[0]] = ing[2]

    cum_usage = defaultdict(float)

    for day_i in range(total_meals):
        base_r = candidate_recipes[day_i % num_cand]
        day_num = day_i + 1

        scaled_ingredients = []
        for ing_name, qty, unit, storage, prod_name, spec, price, query in base_r["base_ingredients"]:
            scaled_qty = round(qty * people_count, 1)
            if scaled_qty == int(scaled_qty):
                scaled_qty = int(scaled_qty)
            scaled_ingredients.append(f"{ing_name} {scaled_qty}{unit}")

        scaled_cal = round(base_r["cal"] * (1.0 if people_count == 1 else (1.0 + 0.8 * (people_count - 1))), 1)
        scaled_prot = round(base_r["prot"] * people_count, 1)

        # 1단계, 2단계 접두사 완전 제거
        clean_steps = [re.sub(r'^(?:【\d+단계(?::\s*[^】]+)?】|\d+단계:\s*)\s*', '', s) for s in base_r["steps"]]

        # 동적 식재료 누적 소진율 & 소진 트래커 계산 (3% ~ 100%)
        progress_pct = min(100, max(3, round((day_num / total_meals) * 100)))

        # 정밀 100% 소진 트래커 생성
        day_parts = []
        tracked_ings = [ing for ing in base_r["base_ingredients"] if ing[3] != "seasoning"]
        # 꽃빵, 두부, 고기 등 핵심 재료 우선 트래킹
        tracked_ings.sort(key=lambda x: 0 if any(k in x[0] for k in ["꽃빵", "두부", "순두부", "가지", "파프리카", "번", "바게트", "생면", "등심", "삼겹", "우삼겹", "부채살", "살", "고기"]) else 1)
        for ing in tracked_ings[:3]:
            name, qty, unit = ing[0], ing[1] * people_count, ing[2]
            cum_usage[name] += qty
            total_for_ing = ing_totals[name]
            pct = min(100, round((cum_usage[name] / total_for_ing) * 100)) if total_for_ing > 0 else 100

            qty_str = f"{int(qty)}" if qty == int(qty) else f"{qty:.1f}"
            cum_str = f"{int(cum_usage[name])}" if cum_usage[name] == int(cum_usage[name]) else f"{cum_usage[name]:.1f}"
            tot_str = f"{int(total_for_ing)}" if total_for_ing == int(total_for_ing) else f"{total_for_ing:.1f}"

            if pct >= 100:
                day_parts.append(f"{name} {qty_str}{unit} 소진 (누적 {cum_str}/{tot_str}{unit}, 100% 완판 소진!)")
            else:
                day_parts.append(f"{name} {qty_str}{unit} 소진 (누적 {cum_str}/{tot_str}{unit}, {pct}%)")

        waste_desc = f"누적 {progress_pct}% 식단 소진 | " + ", ".join(day_parts)

        final_recipes.append({
            "day": day_num,
            "title": f"{base_r['title']} ({people_count}인분)",
            "base_title": base_r["title"],
            "cuisine": base_r["cuisine"],
            "flag": base_r["flag"],
            "cal": str(scaled_cal),
            "carb": str(round(base_r["carb"] * people_count, 1)),
            "prot": str(scaled_prot),
            "fat": str(round(base_r["fat"] * people_count, 1)),
            "ingredients": scaled_ingredients,
            "waste": waste_desc,
            "steps": clean_steps,
            "tip": f"{base_r['tip']}"
        })

    # 4. 장바구니 품목 DB (allProducts) & 4주 분할 계산
    # 모든 품목은 30일 레시피와 100% 연결된 품목으로만 구성 (임의의 보충 품목 원천 차단)
    raw_pantry = [x.strip() for x in re.split(r'[,/ ]+', str(pantry)) if x.strip() and x.strip() not in ["아무것도 없음", "없음", "-"]]

    def build_products_database(recipes_list, current_budget):
        if current_budget >= 400000:
            target_min = int(current_budget * 0.85)
            target_max = int(current_budget * 0.98)
        elif current_budget >= 250000:
            target_min = int(current_budget * 0.80)
            target_max = int(current_budget * 0.95)
        else:
            target_min = int(current_budget * 0.75)
            target_max = int(current_budget * 0.95)

        # 1. 30일 레시피에서 요구하는 식재료 수집
        ing_map = {}
        for r in recipes_list:
            day = r["day"]
            week = min(4, (day - 1) // 7 + 1)
            matched_orig = next((orig for orig in MASTER_RECIPES if orig["title"] in r["title"] or orig["title"] == r.get("base_title")), None)
            if not matched_orig:
                continue

            for ing_name, qty, unit, storage, prod_name, spec, price, query in matched_orig["base_ingredients"]:
                if prod_name not in ing_map:
                    ing_map[prod_name] = {
                        "name": prod_name,
                        "spec": spec,
                        "price": price,
                        "storage": storage,
                        "query": query,
                        "days": [],
                        "weeks": set(),
                        "recipes": [],
                        "first_day": day
                    }
                ing_map[prod_name]["days"].append(day)
                ing_map[prod_name]["weeks"].add(week)
                lbl = f"Day {day} {matched_orig['title'].split()[0]}"
                if "recipe_labels" not in ing_map[prod_name]:
                    ing_map[prod_name]["recipe_labels"] = []
                ing_map[prod_name]["recipe_labels"].append((day, lbl))
                if lbl not in ing_map[prod_name]["recipes"] and len(ing_map[prod_name]["recipes"]) < 4:
                    ing_map[prod_name]["recipes"].append(lbl)

        def get_labels_for_weeks(info, start_w, end_w):
            sub_lbls = []
            for d, lbl in info.get("recipe_labels", []):
                d_w = min(4, (d - 1) // 7 + 1)
                if start_w <= d_w <= end_w and lbl not in sub_lbls:
                    sub_lbls.append(lbl)
            if not sub_lbls:
                return ""
            return ", ".join(sub_lbls[:3])

        # 2. 쌀 기본 배정 (30일 전 식단 밥, 항상 1주차 배정)
        rice_name = "임금님표이천 쌀 상등급 (10kg)" if current_budget >= 400000 else ("곰곰 2024년 햅쌀 (4kg)" if current_budget >= 250000 else "임금님표이천 쌀 상등급 (2kg)")
        rice_price = 34900 if current_budget >= 400000 else (14900 if current_budget >= 250000 else 10800)
        rice_spec = "10kg 1포" if current_budget >= 400000 else ("4kg 1포" if current_budget >= 250000 else "2kg 1포")
        ing_map[rice_name] = {
            "name": rice_name,
            "spec": rice_spec,
            "price": rice_price,
            "storage": "seasoning",
            "query": rice_name,
            "days": [1],
            "weeks": {1},
            "recipes": ["30일 전 식단 밥"],
            "recipe_labels": [(1, "Day 1 공깃밥")],
            "first_day": 1
        }

        # 3. 1차 기본 구매 품목 구성 (Primary Packs)
        # - 조미료: 무조건 1주차
        # - 신선/냉동: 해당 품목이 최초로 조리되는 주차(first_week)에 반드시 배송! (꽃빵 -> 2주차)
        NON_DUPLICABLE = ["꽃빵", "햄버거번", "바게트", "가지", "파프리카", "두부", "순두부", "청경채"]

        cart_items = []
        for prod_name, info in ing_map.items():
            st = info["storage"]
            min_w = 1 if st == "seasoning" else min(info["weeks"])
            weeks_str = f"{min(info['weeks'])}~{max(info['weeks'])}주차" if min(info['weeks']) != max(info['weeks']) else f"{min(info['weeks'])}주차"
            cat = "🧂 조미료" if st == "seasoning" else ("🥬 신선식품" if st == "fresh" else "❄️ 냉동식품")
            cart_items.append({
                "name": prod_name,
                "spec": info["spec"],
                "unitPrice": info["price"],
                "qty": 1,
                "total": info["price"],
                "storage": st,
                "cat": cat,
                "orderWeek": min_w,
                "weeks": weeks_str,
                "recipes": ", ".join(info["recipes"]),
                "query": info["query"],
                "first_day": info["first_day"]
            })

        # 4. 신선 보관 유통기한 품목의 주차별 순환 신선 보충 (두부, 순두부, 청경채 등)
        for prod_name, info in ing_map.items():
            if info["storage"] == "fresh":
                first_w = min(info["weeks"])
                if "두부" in prod_name and "순두부" not in prod_name:
                    for later_w in [2, 4]:
                        if later_w > first_w and later_w in info["weeks"]:
                            sub_rec = get_labels_for_weeks(info, later_w, later_w)
                            if sub_rec:
                                cart_items.append({
                                    "name": f"{prod_name} [{later_w}주차 신선보충]",
                                    "spec": info["spec"],
                                    "unitPrice": info["price"],
                                    "qty": 1,
                                    "total": info["price"],
                                    "storage": "fresh",
                                    "cat": "🥬 신선식품",
                                    "orderWeek": later_w,
                                    "weeks": f"{later_w}주차",
                                    "recipes": f"{later_w}주차 마파두부 소진용 ({sub_rec})",
                                    "query": info["query"],
                                    "first_day": (later_w - 1) * 7 + 1
                                })
                elif "순두부" in prod_name:
                    for later_w in [2, 4]:
                        if later_w > first_w and later_w in info["weeks"]:
                            sub_rec = get_labels_for_weeks(info, later_w, later_w)
                            if sub_rec:
                                cart_items.append({
                                    "name": f"{prod_name} [{later_w}주차 신선보충]",
                                    "spec": info["spec"],
                                    "unitPrice": info["price"],
                                    "qty": 1,
                                    "total": info["price"],
                                    "storage": "fresh",
                                    "cat": "🥬 신선식품",
                                    "orderWeek": later_w,
                                    "weeks": f"{later_w}주차",
                                    "recipes": f"{later_w}주차 순두부탕 소진용 ({sub_rec})",
                                    "query": info["query"],
                                    "first_day": (later_w - 1) * 7 + 1
                                })
                elif "청경채" in prod_name:
                    for later_w in [2, 3, 4]:
                        if later_w > first_w and later_w in info["weeks"]:
                            sub_rec = get_labels_for_weeks(info, later_w, later_w)
                            if sub_rec:
                                cart_items.append({
                                    "name": f"{prod_name} [{later_w}주차 신선보충]",
                                    "spec": info["spec"],
                                    "unitPrice": info["price"],
                                    "qty": 1,
                                    "total": info["price"],
                                    "storage": "fresh",
                                    "cat": "🥬 신선식품",
                                    "orderWeek": later_w,
                                    "weeks": f"{later_w}주차",
                                    "recipes": f"{later_w}주차 청경채 소진용 ({sub_rec})",
                                    "query": info["query"],
                                    "first_day": (later_w - 1) * 7 + 1
                                })

        # 5. 다인 가구(2명 이상) 배율 적용
        if people_count >= 2:
            mult = min(3, people_count)
            for item in cart_items:
                if item["storage"] != "seasoning":
                    item["qty"] *= mult
                    item["total"] = item["unitPrice"] * item["qty"]

        # 6. 예산 맞춤 수량 스케일링 (절대 예산 초과 금지, 레시피 실제 단백질/신선채소만 사용)
        def already_in_week(name, target_week):
            base_name = name.split(" [")[0]
            return any(item["name"].split(" [")[0] == base_name and item["orderWeek"] == target_week for item in cart_items)

        scalable = []
        for prod_name, info in ing_map.items():
            if any(nd in prod_name for nd in NON_DUPLICABLE):
                continue
            if info["storage"] in ["fresh", "frozen"]:
                scalable.append(info)

        def sort_key(x):
            is_prot = any(k in x["name"] for k in ["살", "고기", "육", "등심", "삼겹", "우삼겹", "새우", "연어", "바지락", "해물", "치킨", "대란", "생면"])
            return (0 if is_prot else 1, -x["price"])

        scalable.sort(key=sort_key)

        current_spent = sum(item["total"] for item in cart_items)
        if current_spent < target_min:

            # 2주차 신선보충: 1주차 첫 배송 후 2주차(Day 8~14)에 연속 조리되는 신선육류/채소 보충
            for p_info in scalable:
                if current_spent >= target_min:
                    break
                if already_in_week(p_info["name"], 2):
                    continue
                if min(p_info["weeks"]) == 1 and 2 in p_info["weeks"] and current_spent + p_info["price"] <= target_max:
                    sub_rec = get_labels_for_weeks(p_info, 2, 2)
                    if not sub_rec:
                        continue
                    cart_items.append({
                        "name": f"{p_info['name']} [2주차 신선보충]",
                        "spec": p_info["spec"],
                        "unitPrice": p_info["price"],
                        "qty": 1,
                        "total": p_info["price"],
                        "storage": p_info["storage"],
                        "cat": "🥬 신선식품" if p_info["storage"] == "fresh" else "❄️ 냉동식품",
                        "orderWeek": 2,
                        "weeks": "2주차",
                        "recipes": f"2주차 식단 소진용 ({sub_rec})",
                        "query": p_info["query"],
                        "first_day": 8
                    })
                    current_spent += p_info["price"]

            # 3주차 2차 신선보충: 3주차 또는 4주차에 실제 조리되는 식재료 중 3주차 조리품목
            for p_info in scalable:
                if current_spent >= target_min:
                    break
                if already_in_week(p_info["name"], 3):
                    continue
                if 3 in p_info["weeks"] and current_spent + p_info["price"] <= target_max:
                    sub_rec = get_labels_for_weeks(p_info, 3, 4)
                    if not sub_rec:
                        continue
                    cart_items.append({
                        "name": f"{p_info['name']} [3주차 2차 신선보충]",
                        "spec": p_info["spec"],
                        "unitPrice": p_info["price"],
                        "qty": 1,
                        "total": p_info["price"],
                        "storage": p_info["storage"],
                        "cat": "🥬 신선식품" if p_info["storage"] == "fresh" else "❄️ 냉동식품",
                        "orderWeek": 3,
                        "weeks": "3~4주차",
                        "recipes": f"3~4주차 후반 소진용 ({sub_rec})",
                        "query": p_info["query"],
                        "first_day": 15
                    })
                    current_spent += p_info["price"]

        if current_spent < target_min:
            # 4주차 파이널 보충: 4주차에 실제 조리되는 식재료만 보충
            for p_info in scalable:
                if current_spent >= target_min:
                    break
                if already_in_week(p_info["name"], 4):
                    continue
                if 4 in p_info["weeks"] and current_spent + p_info["price"] <= target_max:
                    sub_rec = get_labels_for_weeks(p_info, 4, 4)
                    if not sub_rec:
                        continue
                    cart_items.append({
                        "name": f"{p_info['name']} [4주차 파이널 보충]",
                        "spec": p_info["spec"],
                        "unitPrice": p_info["price"],
                        "qty": 1,
                        "total": p_info["price"],
                        "storage": p_info["storage"],
                        "cat": "🥬 신선식품" if p_info["storage"] == "fresh" else "❄️ 냉동식품",
                        "orderWeek": 4,
                        "weeks": "4주차",
                        "recipes": f"4주차 완판 소진용 ({sub_rec})",
                        "query": p_info["query"],
                        "first_day": 22
                    })
                    current_spent += p_info["price"]

        # 6-1. 쿠팡 로켓프레시 주차별 최소 주문 금액 가드 (각 주차 주문액 >= 15,000원 충족)
        for w in [2, 3, 4]:
            w_spent = sum(item["total"] for item in cart_items if item["orderWeek"] == w)
            if 0 < w_spent < 15000:
                for p_info in scalable:
                    if w_spent >= 15000:
                        break
                    if already_in_week(p_info["name"], w):
                        continue
                    if w in p_info["weeks"] and current_spent + p_info["price"] <= target_max:
                        sub_rec = get_labels_for_weeks(p_info, w, 4)
                        if not sub_rec:
                            continue
                        tag_name = f"[{w}주차 파이널 보충]" if w == 4 else f"[{w}주차 신선보충]"
                        cart_items.append({
                            "name": f"{p_info['name']} {tag_name}",
                            "spec": p_info["spec"],
                            "unitPrice": p_info["price"],
                            "qty": 1,
                            "total": p_info["price"],
                            "storage": p_info["storage"],
                            "cat": "🥬 신선식품" if p_info["storage"] == "fresh" else "❄️ 냉동식품",
                            "orderWeek": w,
                            "weeks": f"{w}주차",
                            "recipes": f"{w}주차 완판 소진용 ({sub_rec})",
                            "query": p_info["query"],
                            "first_day": (w - 1) * 7 + 1
                        })
                        current_spent += p_info["price"]
                        w_spent += p_info["price"]

        # 6-2. 만약 조리 품목 부족 등으로 15,000원 미만인 주차가 남는다면 이전 주차로 안전 병합
        for w in [4, 3, 2]:
            w_items = [item for item in cart_items if item["orderWeek"] == w]
            w_spent = sum(item["total"] for item in w_items)
            if 0 < w_spent < 15000:
                for item in w_items:
                    item["orderWeek"] = w - 1
                    item["weeks"] = f"{w-1}~{w}주차"

        # 7. 엄격한 예산 한도 준수 (Budget Guard) - 절대 정한 예산 초과 불가
        while current_spent > current_budget:
            removed = cart_items.pop()
            current_spent -= removed["total"]

        # 8. 팬트리 보유 식재료 공제 및 장바구니 리스트 빌드
        products_list = []
        tot_spent = 0
        tot_saved_pantry = 0

        sorted_items = sorted(cart_items, key=lambda x: (x["orderWeek"], 0 if x["storage"] == "seasoning" else 1, x["first_day"]))

        for idx, item in enumerate(sorted_items):
            is_in_pantry = any(p in item["name"] or p in item["query"] for p in raw_pantry)
            buy_qty = item["qty"] if not is_in_pantry else 0
            item_total = (item["unitPrice"] * buy_qty)

            if is_in_pantry:
                tot_saved_pantry += item["unitPrice"] * item["qty"]
                display_name = f"{item['name']} [🏠 보유 재료 0원 공제]"
            else:
                tot_spent += item_total
                display_name = item["name"]

            products_list.append({
                "id": idx + 1,
                "orderWeek": item["orderWeek"],
                "storage": item["storage"],
                "cat": item["cat"],
                "name": display_name,
                "spec": item["spec"],
                "qty": buy_qty,
                "unitPrice": item["unitPrice"] if not is_in_pantry else 0,
                "total": item_total,
                "weeks": item["weeks"],
                "recipes": item["recipes"],
                "query": item["query"]
            })

        week_totals = {
            1: sum(p["total"] for p in products_list if p["orderWeek"] == 1),
            2: sum(p["total"] for p in products_list if p["orderWeek"] == 2),
            3: sum(p["total"] for p in products_list if p["orderWeek"] == 3),
            4: sum(p["total"] for p in products_list if p["orderWeek"] == 4)
        }

        return products_list, tot_spent, tot_saved_pantry, week_totals

    products, total_spent, total_saved_pantry, week_totals = build_products_database(final_recipes, budget)

    # 5. 엄격한 예산 한도 준수 (Budget Guard)
    # 정한 예산을 단 1원도 초과할 수 없음!
    if total_spent > budget:
        # 고비용 품목의 수량을 조정하여 예산 이하로 정확히 컷
        diff = total_spent - budget
        for p in reversed(products):
            if diff <= 0:
                break
            if p["total"] > 0 and p["qty"] > 1:
                reduce_qty = min(p["qty"] - 1, (diff // p["unitPrice"]) + 1)
                p["qty"] -= reduce_qty
                p["total"] = p["qty"] * p["unitPrice"]
                diff -= reduce_qty * p["unitPrice"]
        total_spent = sum(p["total"] for p in products)
        week_totals = {
            1: sum(p["total"] for p in products if p["orderWeek"] == 1),
            2: sum(p["total"] for p in products if p["orderWeek"] == 2),
            3: sum(p["total"] for p in products if p["orderWeek"] == 3),
            4: sum(p["total"] for p in products if p["orderWeek"] == 4)
        }

    saved_from_budget = max(0, budget - total_spent)

    # 6. cart.html을 위한 weekData 생성
    week_data = {}
    for w in range(1, 5):
        start_d = (w - 1) * 7 + 1
        end_d = 30 if w == 4 else w * 7
        w_meals = []
        for r in final_recipes:
            if start_d <= r["day"] <= end_d:
                day_num = r["day"]
                progress_pct = min(100, max(3, round((day_num / total_meals) * 100)))

                main_parts = []
                for ing in r["ingredients"][:2]:
                    parts = ing.split()
                    if len(parts) >= 2:
                        main_parts.append(f"{parts[0]} {parts[1]}")
                    else:
                        main_parts.append(ing)
                today_used = ", ".join(main_parts)

                if day_num < total_meals:
                    meal_desc = f"식재료 누적 {progress_pct}% 소진 (오늘: {today_used})"
                else:
                    meal_desc = "식재료 100% 전량 완판 소진 (음식물 쓰레기 0% 달성!)"

                w_meals.append({
                    "day": f"Day {r['day']}",
                    "tag": r["flag"],
                    "name": r["title"],
                    "chef": "",
                    "cal": r["cal"],
                    "carb": r["carb"],
                    "prot": r["prot"],
                    "fat": r["fat"],
                    "desc": meal_desc
                })

        freezer_msgs = {
            1: f"🧊 <strong>1주차 주문 ({week_totals.get(1,0):,}원)</strong>: 1주차 신선 식재료와 양념류를 수납합니다. 소형 냉동실 한 칸에 여유 있게 쏙 들어갑니다!",
            2: f"🧊 <strong>2주차 주문 ({week_totals.get(2,0):,}원)</strong>: 1주차 재료가 소진된 빈자리에 2주차 신선 단백질과 채소가 신선하게 보충됩니다!",
            3: f"🧊 <strong>3주차 주문 ({week_totals.get(3,0):,}원)</strong>: 3주차 맞춤 식재료가 도착하여 냉동실 적체 없이 쾌적하게 조리합니다!",
            4: f"🧊 <strong>4주차 주문 ({week_totals.get(4,0):,}원)</strong>: 잔여 식재료를 100% 소진하여 피날레 0% 쓰레기 완판을 달성합니다!"
        }

        week_data[w] = {
            "title": f"{w}주차 식단 (Day {start_d} ~ Day {end_d})",
            "freezerMsg": freezer_msgs.get(w, ""),
            "meals": w_meals
        }

    return {
        "client_name": client_name,
        "household": household,
        "people_count": people_count,
        "budget": budget,
        "total_spent": total_spent,
        "saved_from_budget": saved_from_budget,
        "total_saved_pantry": total_saved_pantry,
        "total_meals": total_meals,
        "concept": concept,
        "cuisine": cuisine,
        "exclude": exclude,
        "pantry": pantry,
        "recipes": final_recipes,
        "products": products,
        "week_totals": week_totals,
        "week_data": week_data
    }
