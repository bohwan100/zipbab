# Helper to format recipe dict to Python string
def format_recipes_to_code(recipes):
    import pprint
    lines = []
    for r in recipes:
        lines.append("    {")
        lines.append(f'        "id": "{r["id"]}",')
        lines.append(f'        "title": "{r["title"]}",')
        lines.append(f'        "cuisine": "{r["cuisine"]}", "flag": "{r["flag"]}", "tier": "{r["tier"]}",')
        lines.append(f'        "concepts": {r["concepts"]},')
        lines.append(f'        "allergens": {r["allergens"]},')
        lines.append(f'        "cal": {r["cal"]}, "carb": {r["carb"]}, "prot": {r["prot"]}, "fat": {r["fat"]},')
        lines.append('        "base_ingredients": [')
        for ing in r["base_ingredients"]:
            lines.append(f'            {ing!r},')
        if lines[-1].endswith(','):
            lines[-1] = lines[-1][:-1]
        lines.append('        ],')
        lines.append('        "steps": [')
        for step in r["steps"]:
            lines.append(f'            {step!r},')
        if lines[-1].endswith(','):
            lines[-1] = lines[-1][:-1]
        lines.append('        ],')
        lines.append(f'        "tip": {r["tip"]!r}')
        lines.append("    },")
    return "\n".join(lines)

